    private static HandbookEntry entry(String id, String title, String summary, int order,
                                       List<String> keywords, HandbookPage... pages) {
        return new HandbookEntry(key(id), CATEGORY, title, summary, keywords, order, "town.use", List.of(pages));
    }

    private static HandbookPage page(String title, HandbookBlock... blocks) {
        return new HandbookPage(title, List.of(blocks));
    }

    private static HandbookBlock text(String text) { return HandbookBlock.text(text); }
    private static HandbookBlock link(String label, String id) { return new HandbookBlock.Link(label, key(id)); }
    private static HandbookBlock command(String label, String command) { return new HandbookBlock.Command(label, command); }
    private static NamespacedKey key(String id) { return new NamespacedKey("town", id); }
    private static String amount(double value) { return BigDecimal.valueOf(value).stripTrailingZeros().toPlainString(); }
